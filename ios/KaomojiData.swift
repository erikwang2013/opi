    /// 解析：首现顺序归并、坏行跳过、`start` 累计（纯函数，口径同 Android）。
    static func parse(_ rows: [(String, String)]) -> [Category] {
        var order: [String] = []
        var byLabel: [String: [String]] = [:]
        for (text, label) in rows {
            if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { continue }
            if label.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { continue }
            if byLabel[label] == nil {
                order.append(label)
                byLabel[label] = []
            }
            byLabel[label]?.append(text)
        }
        var start = 0
        var out: [Category] = []
        for label in order {
            let items = byLabel[label] ?? []
            out.append(Category(label: label, start: start, items: items))
            start += items.count
        }
        return out
    }

    /// 全部分类（首次访问时解析一次）。
    static let categories: [Category] = parse(rows)

    /// 拼平后的全部颜文字（浏览/搜索共用的同一序）。
    static let all: [String] = categories.flatMap { $0.items }
