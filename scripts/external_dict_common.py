"""外部词库转换器的共用工具（2026-10-26）。

两个转换器（`convert_custom_pinyin_dictionary.py` / `convert_rime_dict.py`）共用
这里的**输出契约**，因为那份契约不是本脚本定的：`engine-data/src/dict_text.rs` 的
`load_extra_dict` 读 `词<TAB>拼音[<TAB>频次]`，跳过 `#` 注释与 rime front-matter，
拼音必须 ASCII、≤255 字节（`word` 也是 ≤255 字节），重复 (拼音, 词) 取最大频次。
输出头部写 `#` 注释即满足「署名与许可元数据随产物走」；装载器会静默跳过它们。

本模块**不联网、不依赖第三方包**（Python 标准库），也不读仓库里的数据文件。
"""
from __future__ import annotations

import hashlib
import math
import os
import re
import tempfile
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Iterable

# 与 engine-data 的解析器同一组边界（`dict_text.rs`：u8::MAX 字节、u32 词频）。
MAX_FIELD_BYTES = 255
U32_MAX = 0xFFFFFFFF
DEFAULT_FREQ = 1000

_PINYIN_RE = re.compile(r"[a-z]+")


@dataclass
class Entry:
    """一条候选：(词, 无调连写拼音, 词频)。`order` 只用于稳定排序/截断。"""

    word: str
    pinyin: str
    freq: int
    order: int


@dataclass
class WriteStats:
    written: int
    dropped_by_entries: int
    dropped_by_bytes: int
    total_unique: int
    bytes_written: int


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def normalize_pinyin(code: str) -> str:
    """带调/数字调/ü 冒号拼音 → 无调、ü→v、小写、去音节分隔。

    顺序与 `scripts/hanzi_freq.py::normalize` 同源：**ü 家族必须在 NFD 之前**映射
    成 v —— NFD 之后组合音调符被剥离，就分不清 u/ü 了（nǚ→nu 而不是 nv）。
    Rime 的 code 用空格分音节、有些词库用 `'`，本仓词库键是连写（nihao），故都去掉。
    """
    py = code.replace("u:", "v")
    py = re.sub(r"[üǖǘǚǜ]", "v", py)
    py = unicodedata.normalize("NFD", py)
    py = "".join(c for c in py if not unicodedata.combining(c))
    py = re.sub(r"[0-9]", "", py).lower()
    return re.sub(r"[\s'’]+", "", py)


def valid_word(word: str) -> bool:
    return bool(word) and len(word.encode("utf-8")) <= MAX_FIELD_BYTES


def valid_pinyin(pinyin: str) -> bool:
    # 与 `dict_text.rs` 同口径：ASCII、非空、≤255 字节。`[a-z]+` 比它更严一点，
    # 是为了不把 `ni3hao` / 带调残留塞进连写键（引擎查询键只有 a-z）。
    return bool(_PINYIN_RE.fullmatch(pinyin)) and len(pinyin.encode("ascii")) <= MAX_FIELD_BYTES


def parse_weight(raw: str) -> tuple[int, bool]:
    """Rime 第三列 → 词频。返回 `(freq, ok)`；`ok=False` 表示原值不是合法权重。

    与 Rust `dict_text::parse_freq` 对齐：纯整数直取；`NN.NN%` 按
    `round(percent × 1000)`。Rust 的 `f64::round` 是「半数远离零」，Python 的
    `round()` 是银行家舍入，故这里用 `floor(x + 0.5)` 显式对齐。
    非法/越界值**不丢词**：回落到 [`DEFAULT_FREQ`] 并让调用方计数（上游有 `6N`
    这种手滑权重，丢词比降级更糟）。
    """
    s = raw.strip()
    if not s:
        return DEFAULT_FREQ, True
    if re.fullmatch(r"\d+", s):
        n = int(s)
        return (n, True) if n <= U32_MAX else (DEFAULT_FREQ, False)
    m = re.fullmatch(r"(\d+(?:\.\d+)?)%", s)
    if m:
        n = int(math.floor(float(m.group(1)) * 1000.0 + 0.5))
        return (n, True) if n <= U32_MAX else (DEFAULT_FREQ, False)
    return DEFAULT_FREQ, False


def add_entry(best: dict[tuple[str, str], Entry], entry: Entry) -> bool:
    """按 `(词, 拼音)` 去重、同键取最大词频。返回是否新增了一个键。

    同词不同读音**都保留**（`行` 的 hang/xing 是单库合法语义，合并层也按
    `(拼音, 词)` 判重，见 `engine-core/src/dict_layers.rs`）。
    """
    key = (entry.word, entry.pinyin)
    old = best.get(key)
    if old is None:
        best[key] = entry
        return True
    if entry.freq > old.freq:
        old.freq = entry.freq
    if entry.order < old.order:
        old.order = entry.order
    return False


def shortest_first(entry: Entry) -> tuple:
    """无权重源的截断顺序：短词优先（更可能是基础词），再按拼音/词稳定排序。"""
    return (len(entry.word), entry.pinyin, entry.word)


def weight_first(entry: Entry) -> tuple:
    """有 权重源的截断顺序：高频先（保留上游 sort: by_weight 的意图）。"""
    return (-entry.freq, len(entry.word), entry.pinyin, entry.word)


def header_lines(
    *,
    generator: str,
    source_lines: Iterable[str],
    license_lines: Iterable[str],
    change_lines: Iterable[str],
    stats_line: str,
) -> list[str]:
    """构造 `#` 头部。所有行都以 `# ` 开头（空行是单个 `#`），装载器会跳过。"""
    out = [
        "# OPI extra dictionary — TAB-separated: word<TAB>pinyin[<TAB>freq]",
        f"# Generated by {generator}; do not edit by hand.",
        "#",
    ]
    out += [f"# {line}" if line else "#" for line in source_lines]
    out.append("#")
    out += [f"# {line}" if line else "#" for line in license_lines]
    out.append("#")
    out += [f"# {line}" if line else "#" for line in change_lines]
    out.append(f"# {stats_line}")
    return out


def _render(entry: Entry, three_columns: bool) -> str:
    if three_columns:
        return f"{entry.word}\t{entry.pinyin}\t{entry.freq}\n"
    return f"{entry.word}\t{entry.pinyin}\n"


def write_tsv(
    path: Path,
    entries: Iterable[Entry],
    header_fn: Callable[[int, int, int], list[str]],
    *,
    max_entries: int,
    max_bytes: int,
    priority: Callable[[Entry], tuple],
    three_columns: bool,
) -> WriteStats:
    """排序 →（条数/字节双上限）截断 → 原子写。

    `max_entries=0` / `max_bytes=0` = 不设限。字节上限把**表头也算进去**（导入面
    检查的是整份文件大小）。表头里带最终计数，所以截断后要重算一次头部；最多迭代
    8 次（每次至少少一行，必然收敛）。
    """
    ordered = sorted(entries, key=priority)
    total = len(ordered)
    entry_cap = total if max_entries == 0 else min(max_entries, total)
    dropped_by_entries = total - entry_cap
    selected = ordered[:entry_cap]
    dropped_by_bytes = 0
    lines: list[str] = []
    header: list[str] = []

    for _ in range(8):
        header = header_fn(len(selected), dropped_by_entries, dropped_by_bytes)
        header_bytes = sum(len(line.encode("utf-8")) + 1 for line in header)
        if max_bytes and header_bytes > max_bytes:
            raise ValueError(
                f"字节上限 {max_bytes} 连表头都放不下（表头 {header_bytes} 字节）；"
                "调大 --max-output-mb 或调小表头"
            )
        budget = None if max_bytes == 0 else max_bytes - header_bytes
        lines = []
        used = 0
        for entry in selected:
            line = _render(entry, three_columns)
            size = len(line.encode("utf-8"))
            if budget is not None and used + size > budget:
                break
            lines.append(line)
            used += size
        if len(lines) == len(selected):
            break
        dropped_by_bytes = len(selected) - len(lines)
        selected = selected[: len(lines)]
    else:
        raise RuntimeError("字节上限迭代 8 次仍未收敛（表头长度异常）")

    header = header_fn(len(selected), dropped_by_entries, dropped_by_bytes)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent)
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(header) + "\n")
            f.writelines(lines)
        os.replace(tmp_name, path)
    except BaseException:
        try:
            os.unlink(tmp_name)
        except FileNotFoundError:
            pass
        raise
    size = path.stat().st_size
    return WriteStats(
        written=len(selected),
        dropped_by_entries=dropped_by_entries,
        dropped_by_bytes=dropped_by_bytes,
        total_unique=total,
        bytes_written=size,
    )
